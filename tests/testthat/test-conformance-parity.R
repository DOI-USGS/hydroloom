test_that("the committed parity table is current", {
  skip_if_no_conformance()
  skip_if_not_installed("yaml")

  manifest <- read_conformance_yaml(file.path(conformance_dir(), "manifest.yaml"))
  lines <- parity_lines(manifest)

  if (write_expected_mode()) write_parity(lines)

  expect_true(file.exists(parity_file()))
  expect_identical(readLines(parity_file(), warn = FALSE, encoding = "UTF-8"), lines)
})

test_that("every R-generated case lists r and every function has cases", {
  skip_if_no_conformance()
  skip_if_not_installed("yaml")

  # M2 asserted every function `r` only; ROADMAP M5 Done-when moves the
  # phase-1 functions to `r, python`. R stays the generator, so every case R
  # generates still lists r (S-7); a Python-only case (`supported_by:
  # [python]`, RULES B-5) is generated by Python and counted apart.
  manifest <- read_conformance_yaml(file.path(conformance_dir(), "manifest.yaml"))
  rows <- parity_rows(manifest)

  r_generated <- Filter(function(x) "r" %in% unlist(x$generator), manifest$cases)

  expect_true(all(vapply(r_generated, function(x) "r" %in% unlist(x$supported_by), logical(1))))
  expect_true(all(rows$cases > 0))
})

test_that("parity rows take the languages common to every case", {
  m <- list(suite_version = "0.0.0",
    functions = list(a = list(), hy = list(), b = list()),
    cases = list(
      list(id = "a1", `function` = "a", supported_by = list("r", "python")),
      list(id = "a2", `function` = "a", supported_by = list("r")),
      list(id = "h1", `function` = "hy", supported_by = list("python", "r"))))

  rows <- parity_rows(m)

  expect_identical(rows$supported_by, c("r", "r, python", "none"))
  expect_identical(rows$python, c("a", "as_hy", "b"))
  expect_identical(rows$cases, c(2L, 1L, 0L))
  expect_identical(rows$r_only, c(0L, 0L, 0L))
})

test_that("parity rows count r_only cases apart", {
  m <- list(suite_version = "0.0.0",
    functions = list(a = list(), b = list()),
    cases = list(
      list(id = "a1", `function` = "a", supported_by = list("r", "python")),
      list(id = "a2", `function` = "a", supported_by = list("r"), r_only = "a.md §Signature"),
      list(id = "b1", `function` = "b", supported_by = list("r"), r_only = "b.md §Signature")))

  rows <- parity_rows(m)

  expect_identical(rows$supported_by, c("r, python", "r"))
  expect_identical(rows$cases, c(2L, 1L))
  expect_identical(rows$r_only, c(1L, 1L))
})

test_that("parity rows count python-only cases apart", {
  m <- list(suite_version = "0.0.0",
    functions = list(hy = list(), b = list()),
    cases = list(
      list(id = "h1", `function` = "hy", supported_by = list("r", "python")),
      list(id = "h2", `function` = "hy", supported_by = list("python")),
      list(id = "b1", `function` = "b", supported_by = list("r"), r_only = "b.md §Signature"),
      list(id = "b2", `function` = "b", supported_by = list("python"))))

  rows <- parity_rows(m, python_all = character())

  expect_identical(rows$supported_by, c("r, python", "r"))
  expect_identical(rows$cases, c(2L, 2L))
  expect_identical(rows$r_only, c(0L, 1L))
  expect_identical(rows$python_only, c(1L, 1L))
})

test_that("an all r_only function reads r, python when Python exports it", {
  m <- list(suite_version = "0.0.0",
    functions = list(a = list(), hy = list()),
    cases = list(
      list(id = "a1", `function` = "a", supported_by = list("r"), r_only = "a.md §Signature"),
      list(id = "h1", `function` = "hy", supported_by = list("r"), r_only = "hy.md §Signature")))

  expect_identical(parity_rows(m, python_all = "as_hy")$supported_by, c("r", "r, python"))
  expect_identical(parity_rows(m, python_all = character())$supported_by, c("r", "r"))
})

test_that("parity_python_all reads the quoted names of __all__", {
  path <- tempfile(fileext = ".py")
  on.exit(unlink(path))
  writeLines(c("from x import a", "", "__all__ = [", "    \"add_toids\",",
    "    'as_hy',", "]", "other = [\"no\"]"), path)

  expect_identical(parity_python_all(path), c("add_toids", "as_hy"))
  expect_identical(parity_python_all(file.path(tempdir(), "absent.py")), character())
})
